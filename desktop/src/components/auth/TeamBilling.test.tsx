import { act, render, screen, waitFor } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import { afterEach, expect, it, vi } from 'vitest';
import { teamBillingApi, type TeamBillingState } from '../../api/teamBilling';
import { TeamBilling } from './TeamBilling';
const initial: TeamBillingState = { enabled: true, owner: true, executionAllowed: false, separateCosts: 'Model usage and infrastructure are billed separately from the fixed team subscription.', revision: 1, status: 'unsubscribed' };
const quoted: TeamBillingState = { ...initial, revision: 2, quote: { id: 'quote-one', expiresAt: 2000000000, termsUrl: 'https://app.example.com/terms', privacyUrl: 'https://app.example.com/privacy', price: { priceId: 'price_plan', unitAmount: 2400, currency: 'usd', interval: 'month', intervalCount: 1, taxBehavior: 'exclusive' } } };
afterEach(() => vi.restoreAllMocks());
it('requires current price and terms review, reserves once and exposes a verified Stripe destination without granting access', async () => {
  vi.spyOn(teamBillingApi, 'read').mockResolvedValue(initial);
  vi.spyOn(teamBillingApi, 'quote').mockResolvedValue(quoted);
  let finish!: (value: { url: string }) => void;
  const checkout = vi.spyOn(teamBillingApi, 'checkout').mockReturnValue(new Promise(resolve => { finish = resolve; }));
  render(<TeamBilling teamId="team-one" />);
  await userEvent.click(await screen.findByRole('button', { name: 'Review current subscription price' }));
  expect(await screen.findByText(/24.00 per team per month/)).not.toBeNull();
  const prepare = screen.getByRole('button', { name: 'Prepare Stripe checkout' });
  expect((prepare as HTMLButtonElement).disabled).toBe(true);
  await userEvent.click(screen.getByRole('checkbox', { name: /I accept the terms/ }));
  await userEvent.dblClick(prepare);
  expect(checkout).toHaveBeenCalledExactlyOnceWith('team-one', 'quote-one', 2);
  await act(async () => { finish({ url: 'https://checkout.stripe.com/c/pay/cs_fixture' }); });
  expect((await screen.findByRole('link', { name: 'Continue to Stripe checkout' })).getAttribute('href')).toBe('https://checkout.stripe.com/c/pay/cs_fixture');
  expect(screen.getByRole('link', { name: 'Continue to Stripe checkout' }).getAttribute('target')).toBeNull();
  expect(screen.getByText(/New team execution is unavailable/)).not.toBeNull();
  expect(screen.getByText(/Returning from Stripe does not activate access/)).not.toBeNull();
});
it('retains ambiguous checkout errors and recovers the same reservation after reload', async () => {
  vi.spyOn(teamBillingApi, 'read').mockResolvedValue({ ...quoted, revision: 3, checkoutState: 'reserved', checkoutRecoverable: true });
  const checkout = vi.spyOn(teamBillingApi, 'checkout').mockRejectedValue(new Error('Stripe response uncertain; resume this reservation'));
  render(<TeamBilling teamId="team-one" />);
  await screen.findByText(/A checkout reservation already exists/);
  expect(screen.queryByRole('button', { name: 'Review current subscription price' })).toBeNull();
  await userEvent.click(screen.getByRole('checkbox'));
  await userEvent.click(screen.getByRole('button', { name: 'Resume reserved checkout' }));
  expect((await screen.findByRole('alert')).textContent).toContain('resume this reservation');
  expect(checkout).toHaveBeenCalledWith('team-one', 'quote-one', 3);
});
it('keeps cancellation available when execution is suspended and exposes no owner mutations to members', async () => {
  const read = vi.spyOn(teamBillingApi, 'read').mockResolvedValue({ ...initial, status: 'active', hasCustomer: true, canManageSubscription: true });
  const portal = vi.spyOn(teamBillingApi, 'portal').mockResolvedValue({ url: 'https://billing.stripe.com/p/session/fixture' });
  const view = render(<TeamBilling teamId="team-one" />);
  await userEvent.click(await screen.findByRole('button', { name: 'Manage or cancel subscription' }));
  expect(await screen.findByRole('link', { name: 'Open Stripe subscription management' })).not.toBeNull();
  expect(screen.getByRole('link', { name: 'Open Stripe subscription management' }).getAttribute('target')).toBeNull();
  expect(portal).toHaveBeenCalledWith('team-one');
  read.mockResolvedValue({ ...initial, owner: false, status: 'active' });
  view.rerender(<TeamBilling teamId="team-two" />);
  await screen.findByText('A team owner can review pricing, subscribe or cancel.');
  expect(screen.queryByRole('button', { name: 'Manage or cancel subscription' })).toBeNull();
  expect(screen.queryByRole('button', { name: 'Verify subscription with Stripe' })).toBeNull();
});
it('ignores previous-team completion and rejects a provider redirect outside Stripe', async () => {
  let finish!: (value: TeamBillingState) => void;
  const read = vi.spyOn(teamBillingApi, 'read').mockImplementation(id => id === 'team-old' ? new Promise(resolve => { finish = resolve; }) : Promise.resolve(quoted));
  vi.spyOn(teamBillingApi, 'checkout').mockResolvedValue({ url: 'https://checkout.stripe.com.attacker.invalid/steal' });
  const view = render(<TeamBilling teamId="team-old" />);
  await waitFor(() => expect(read).toHaveBeenCalledWith('team-old'));
  view.rerender(<TeamBilling teamId="team-current" />);
  await screen.findByRole('checkbox');
  await act(async () => { finish({ ...initial, owner: false }); });
  await userEvent.click(screen.getByRole('checkbox'));
  await userEvent.click(screen.getByRole('button', { name: 'Prepare Stripe checkout' }));
  expect((await screen.findByRole('alert')).textContent).toContain('invalid Stripe destination');
  expect(screen.queryByRole('link', { name: 'Continue to Stripe checkout' })).toBeNull();
});
